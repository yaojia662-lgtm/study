void main() {
  // 问题 6：位与和位或运算
  print('=== 问题 6 ===');
  int p = 6;  // 二进制：110
  int q = 3;  // 二进制：011
  print('位与运算结果 (p & q) = ${p & q}');  // 110 & 011 = 010 (2)
  print('位或运算结果 (p | q) = ${p | q}');  // 110 | 011 = 111 (7)

  // 问题 7：左移和右移运算
  print('\n=== 问题 7 ===');
  p = 6;      // 二进制：110
  print('左移结果 (p << 1) = ${p << 1}');  // 1100 (12)
  print('右移结果 (p >> 1) = ${p >> 1}');  // 11 (3)

  // 问题 8：三元运算符
  print('\n=== 问题 8 ===');
  int age = 18;
  String result = age >= 20 ? "成人" : "青少年";
  print('年龄 $age 岁：$result');

  // 附加演示：不同年龄的结果
  print('\n--- 附加演示 ---');
  int age2 = 25;
  String result2 = age2 >= 20 ? "成人" : "青少年";
  print('年龄 $age2 岁：$result2');
}